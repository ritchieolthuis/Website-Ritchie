      function startContactTypewriter() {
           const el = document.getElementById('contact-typewriter');
           if (!el) return;
           
           // Get HTML string from translations based on current lang
           let rawHTML = translations[currentLang].contact_title;
           // Expected format: "Prefix <span class="...">Suffix</span>"
           // Regex to extract parts. Handles class with quotes.
           const regex = /^(.*?)<span class="(.*?)">(.*?)<\/span>$/;
           const match = rawHTML.match(regex);
           
           if(!match) {
               el.innerHTML = rawHTML; // Fallback if format doesn't match
               return;
           }
           
           const prefix = match[1]; // "Let's work " or "Laten we "
           const spanClass = match[2];
           const spanText = match[3]; // "Together" or "Samenwerken"
           
           el.innerHTML = "";
           el.classList.add('typewriter-cursor');
           
           let i = 0;
           
           function typePrefix() {
               if (i < prefix.length) {
                   el.innerHTML += prefix.charAt(i);
                   i++;
                   setTimeout(typePrefix, 50);
               } else {
                   // Start typing span part
                   const span = document.createElement('span');
                   span.className = spanClass;
                   el.appendChild(span);
                   let j = 0;
                   function typeSpan() {
                       if(j < spanText.length) {
                           span.textContent += spanText.charAt(j);
                           j++;
                           setTimeout(typeSpan, 50);
                       } else {
                           el.classList.remove('typewriter-cursor');
                       }
                   }
                   typeSpan();
               }
           }
           typePrefix();
      }

